/**
 * The 9 non-chiral Catalan solids with non-uniform edge lengths --
 * exercising `makeSpecByCircumradius` for real for the first time
 * (batch 1's 2 shapes, both rhombi, happened to have uniform edge
 * length despite not needing it). Same polar-reciprocation
 * construction as batch 1: `v' = c * r_mid^2 / |c|^2` for each
 * Archimedean dual's own face centroid `c`, about its own midsphere
 * radius `r_mid`. Verified computationally before trusting it for
 * each shape, not assumed to hold generally: every one of this
 * registry's own Archimedean solids has all of its edge midpoints
 * at EXACTLY the same distance from center (checked directly, min
 * and max differ by less than 1e-6, for every one of the 8
 * Archimedean bases used here) -- the midsphere is genuinely
 * well-defined for each, not just for the edge-transitive ones
 * (cuboctahedron, icosidodecahedron) batch 1 happened to use.
 *
 * Every one of the 9 passed `validateCatalanShape` cleanly on the
 * first attempt: single edge-length signature across all faces of a
 * shape (true face congruence), uniform insphere distance, correct
 * V/E/F matching the standard table exactly.
 *
 * **A real, necessary fix applied before any of these 9 were
 * accepted, not just for batch 1's rhombic triacontahedron**: every
 * face's vertex-0 was checked for a consistent geometric role across
 * all faces of the same shape (the exact bug class documented on
 * RHOMBIC_TRIACONTAHEDRON above) -- and every one of these 9 needed
 * the fix, unlike the dodecahedron which happened to already be
 * consistent. This batch's faces are isosceles/scalene triangles and
 * kites, not rhombi, so the simple "start at the acute corner" rule
 * doesn't generalize as-is; canonicalized instead by rotating each
 * face to start at whichever vertex's own interior angle is both the
 * least frequent among that face's own angle values (breaks ties
 * toward vertices that occur only once, e.g. an isosceles triangle's
 * apex) and, among any remaining ties, the largest such angle --
 * confirmed to reduce every shape to exactly ONE consistent angle
 * value at vertex 0 across all its faces before trusting it (checked
 * per shape, not assumed to work uniformly). This mattered MORE here
 * than for the rhombic triacontahedron: every face in this batch has
 * `faceRotationalSymmetry` of exactly 1 (no non-identity rotation
 * preserves an irregular triangle or kite), so there's no fallback
 * registration to mask a wrong vertex-0 choice the way a rhombus's
 * 2-fold symmetry could.
 */

